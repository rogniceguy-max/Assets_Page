"""Interfaces for the active WPF project-workbook API."""
from __future__ import annotations

from dataclasses import dataclass
from typing import Any, BinaryIO, Protocol


@dataclass(frozen=True)
class StreamAsset:
    stream: BinaryIO
    length: int
    media_type: str
    # Returned stream belongs to HTTP response; sender closes it even on disconnect.


class WorkflowServices(Protocol):
    """Every method enforces host project/file ACL. Missing adapters must raise 503."""
    def projects(self, actor: Any) -> list[dict[str, Any]]: ...
    def list_files(self, actor: Any, project_id: str) -> list[dict[str, Any]]: ...
    def latest_event_sequence(self, project_id: str) -> int: ...
    def wait_for_events(self, project_id: str, sequence: int,
                        timeout: float = 15.0) -> list[dict[str, Any]]: ...
    def rename_workbook(self, actor: Any, file_id: str, expected_name_version: int,
                        display_name: str) -> dict[str, Any]: ...
    def delete_workbook(self, actor: Any, file_id: str) -> dict[str, Any]: ...
    def add_scene_row(self, actor: Any, file_id: str, sheet_id: str) -> dict[str, Any]: ...
    def add_asset_row(self, actor: Any, file_id: str, sheet_id: str) -> dict[str, Any]: ...
    def delete_row(self, actor: Any, file_id: str, row_id: str, expected_version: int,
                   kind: str) -> dict[str, Any]: ...
    def create(self, actor: Any, template_kind: str, project_id: str,
               operation_id: str, name: str | None = None) -> dict[str, Any]: ...
    def list_images(self, actor: Any, project_id: str, q: str | None,
                    category: str | None, cursor: str | None, page_size: int) -> dict[str, Any]: ...
    def upload_image_stream(self, actor: Any, name: str, media_type: str, source: BinaryIO,
                            length: int, project_id: str | None,
                            folder_id: str | None = None,
                            folder_path: str | None = None) -> dict[str, Any]: ...
    def image_metadata(self, actor: Any, image_id: str) -> dict[str, Any]: ...
    def rename_image(self, actor: Any, image_id: str, expected_version: int,
                     display_name: str) -> dict[str, Any]: ...
    def image_content_stream(self, actor: Any, asset_id: str, thumbnail: bool) -> StreamAsset: ...
    def update_scene_row(self, actor: Any, file_id: str, row_id: str, expected_version: Any,
                         changes: Mapping[str, Any]) -> dict[str, Any]: ...
    def update_story_content(self, actor: Any, file_id: str, row_id: str, expected_version: int,
                             story_content: str | None) -> dict[str, Any]: ...
    def update_asset_row(self, actor: Any, file_id: str, row_id: str, expected_version: int,
                         category: str | None, name: str | None) -> dict[str, Any]: ...
    def replace_images(self, actor: Any, file_id: str, row_id: str, expected_version: int,
                        selected_image_id: str | None, candidate_image_ids: list[str]) -> dict[str, Any]: ...
